// tokenState is the Token page's state.
type tokenState struct {
	// Create form.
	name        string
	symbol      string
	supply      string
	decimals    float64
	decimalsErr string
	// nameErr and symbolErr carry the domain's own refusal for the two fields
	// the store bounds. They existed only in the status line before, which names
	// no field; here the sentence sits under the control that needs fixing.
	nameErr   string
	symbolErr string
	// supplyErr carries the parser's refusal for the one field the store reads
	// as a number. Without it a decimal typed into the form travelled all the way
	// to storage and came back as a status-line sentence naming no control.
	supplyErr string
	owner     string
	// ownerPriv is the private half of a key pair generated by the Create card.
	// It is shown once for copying and never stored by the service.
	ownerPriv string
	// ownerKeyTokenID is the token created with ownerPriv. The write forms can
	// reuse that key only while this token is the subject; selecting another
	// token hides the button rather than signing for the wrong owner.
	ownerKeyTokenID string

	// Read forms.
	tokenID string
	// resolvedOwner is the owner already confirmed for resolvedOwnerID by a
	// list selection, token creation or TokenInfo read. Kept separately from
	// the visible page so paging does not erase the subject's owner context.
	resolvedOwner   string
	resolvedOwnerID string
	// subjectID is the token id whose owner context has been applied to the
	// write forms. A manual edit to Token ID can bypass the row-selection path;
	// comparing this value on each frame keeps the old owner, secrets and
	// recipients from remaining under the new subject.
	subjectID string
	// balanceAccount and historyOwner are separate inputs: sharing one field
	// meant typing a history owner silently changed the account the Balance
	// card would read, under a readout fetched for someone else.
	balanceAccount string
	historyOwner   string

	info    *TokenRow
	balance string
	// Each readout is a cache keyed by the inputs that produced it. A
	// selection or create changes tokenID, and a refresh can fail; without
	// the key, rows fetched for the previous token stayed on screen under the
	// new one. The error keeps a failed same-subject refresh visible instead
	// of silently keeping stale rows.
	infoErr      error
	infoLoadedID string
	balanceErr   error
	// balanceLoadedToken/Owner identify the account the shown balance belongs
	// to, so changing either input invalidates it before the read.
	balanceLoadedToken  string
	balanceLoadedOwner  string
	historyErr          error
	historyLoadedToken  string
	historyLoadedOwner  string
	historyLoadedLimit  int
	historyLoadedOffset int

	// Write forms.
	mintTo       string
	mintAmount   string
	mintPriv     string
	xFrom        string
	xTo          string
	xAmount      string
	xPriv        string
	approveOwner string
	approveTo    string
	approveAmt   string
	approvePriv  string
	fromOwner    string
	fromTo       string
	fromAmount   string
	fromPriv     string
	// fromSpender is optional: it is not sent to the service, but lets a
	// remembered signer key be offered for Transfer From.
	fromSpender    string
	burnFrom       string
	burnAmount     string
	burnPriv       string
	allowanceOwner string
	allowanceTo    string
	historyLimit   float64
	historyOffset  float64

	allowance string
	// allowanceErr and the loaded key make an allowance readout follow the
	// token/owner/spender currently shown, like the other Token reads.
	allowanceErr         error
	allowanceLoadedToken string
	allowanceLoadedOwner string
	allowanceLoadedTo    string
	history              []TransferRow

	// tokens is the current page of stored tokens. It lets an operator pick
	// one instead of already knowing its id, while the pager reaches older
	// records without materialising the collection.
	tokens []TokenRow
	// search narrows the list by id, name or symbol while the store grows;
	// appliedSearch is the query the current highlight belongs to.
	search        string
	appliedSearch string
	// chosen is the row chosen in that list, -1 for none.
	chosen int
	// offset pages the collection. hasMore comes from requesting one row past
	// the page, so the last page never leaves a dead Next button behind.
	offset  int
	hasMore bool

	loadErr error

	// askBurn drives the irreversible-burn confirmation. The burn only runs
	// when the operator picks the destructive button, mirroring the CLI's
	// --confirm gate.
	askBurn bool
	// opTab is the operation shown in the write column. Five full forms
	// stacked in one column buried every later action below the fold; one
	// form at a time keeps the subject and the chosen operation visible.
	opTab int
	// createAdvanced and historyAdvanced hold the disclosures for fields that
	// most first uses do not need: token decimals and paging.
	createAdvanced  bool
	historyAdvanced bool

	status statusLine

	// burnTrigger receives focus when the destructive confirmation closes, and
	// generateControl takes it back when the one-time key card is dismissed.
	burnTrigger     ui.Handle
	generateControl ui.Handle
	ownerKeyCopy    ui.Handle
	// loaded records that the first read completed, so an unread page is not
	// mistaken for an empty store. A page switch during a background write skips
	// the read, and the empty-state copy would otherwise claim the store is empty
	// without having looked.
	loaded bool
	// storeEmpty records whether a term-less read found nothing, so an empty
	// result for a search is told apart from an empty store. storeChecked records
	// that the question has been asked, which a query restored from an earlier
	// session has not.
	storeEmpty   bool
	storeChecked bool
}

const tokenPageSize = 100

// loadTokenPage commits the new page offset only after the read succeeds. A
// failed Next/Previous therefore leaves the last good rows labelled with the
// page they actually came from instead of moving the pager under them.
func (a *App) loadTokenPage(offset int) bool {
	if a.services == nil {
		return false
	}
	// A background write owns the database. refresh guards this, but the search
	// field reads on its own when a term changes, which would land on the locked
	// database and report a page failure. The guard sits here, where every list
	// read starts, for the same reason it sits in refresh: a caller that forgets
	// is silent otherwise.
	if a.readBlocked() {
		return false
	}
	// The list is the page's entry point: without it a token created in an
	// earlier session could not be reached at all.
	if offset < 0 {
		offset = 0
	}
	// The search is a storage query, not a filter over the loaded rows: a token
	// whose row is on an older page must be reachable by typing its name. The
	// applied term is the one the rows describe, so a paged move keeps matching
	// what the reader saw when they pressed Next.
	tokens, err := a.services.ListMatchingTokens(a.token.appliedSearch, tokenPageSize+1, offset)
	a.token.loadErr = err
	if err != nil {
		return false
	}
	if len(tokens) == 0 && offset > 0 {
		return a.loadTokenPage(0)
	}
	a.token.loaded = true
	a.token.offset = offset
	// A term-less read says whether the store has anything at all; a term that
	// matches nothing must not be mistaken for an empty store.
	if a.token.appliedSearch == "" {
		a.token.storeEmpty = len(tokens) == 0
	}
	a.token.hasMore = len(tokens) > tokenPageSize
	if a.token.hasMore {
		tokens = tokens[:tokenPageSize]
	}
	a.token.tokens = tokens
	return true
}

// tokenView lays the page out in two columns: the token you are working with
// on the left (list, create, inspect, allowance, history), and the operations
// that change it on the right (mint, transfer, approve, transfer-from, burn).
// Separating reads from writes keeps the five write tabs inside their column
// and every later form below the fold reachable through one stable row.
func (a *App) tokenView(c *ui.Context) {
	a.syncTokenSubject()
	a.scrollPage(c, func() {
		if a.tokenNeedsFirstRecord() {
			twoColumns(c, func() {
				a.tokenCreate(c)
			}, func() {
				firstRunPath(c, pageToken, "No tokens yet",
					"A token starts with its supply and the owner key that signs every later write.",
					"Fill in the create form.",
					"Mint, transfer, approve or burn once the new token is selected.",
					"Read balances, allowances and transfer history.",
				)
			})
			a.renderBurnDialog(c)
			return
		}
		// Four moves, not three: the signing rule and the storage rule are
		// separate steps because neither sentence has to carry the other's
		// subject. A second explanation above this one would repeat them.
		guide(c, &a.guides.token,
			"Select a token in Tokens, or create one. Its owner public key fills the account fields for you.",
			"Choose a write in the action tabs: Mint, Transfer, Approve, Transfer From or Burn. A spender's remaining allowance is in Allowance.",
			"Each write signs with a different key: Mint/Approve/Burn use the owner's, Transfer the sender's, Transfer From the spender's.",
			"Keys are never stored. “Use generated owner key” only works for the token that key created.",
		)
		twoColumns(c, func() {
			a.tokenList(c)
			a.tokenCreate(c)
			a.tokenAllowance(c)
			a.tokenHistory(c)
		}, func() {
			a.tokenWrites(c)
			// Inspect sits under the write tabs: both act on the token the
			// subject strip names, and the collection column already carries
			// the list, create and history cards.
			a.tokenRead(c)
		})
		a.renderBurnDialog(c)
	})
}

// tokenNeedsFirstRecord is true only after a successful empty read. A load
// failure keeps the full page so its warning and any retained rows stay
// visible; a subject entered elsewhere also keeps the write workspace open.
func (a *App) tokenNeedsFirstRecord() bool {
	entered := a.token.search != "" || a.token.appliedSearch != "" ||
		strings.TrimSpace(a.token.tokenID) != "" ||
		a.token.info != nil || a.token.infoLoadedID != "" ||
		a.token.balanceLoadedToken != "" || a.token.historyLoadedToken != "" ||
		a.token.allowanceLoadedToken != "" || a.token.chosen >= 0
	// A page nothing has read yet is not an empty store: the first-run guide
	// invites a create, and it must not appear for a store this page has not
	// looked at. The state is real: navigation is allowed during a background
	// write, and the read is skipped.
	if !a.token.loaded {
		return false
	}
	return firstRecordOnly(a.token.loadErr, len(a.token.tokens), entered)
}

// tokenList draws the stored tokens and lets the operator choose one: a
// choice fills the id every other card acts on, so a token created in an
// earlier session is reachable without remembering its id.
func (a *App) tokenList(c *ui.Context) {
	formCard(c, "Tokens", "Browse stored tokens newest first and choose one as the subject of the cards here.", func() {
		if a.token.loadErr != nil && !loadWarning(c, "Failed to load tokens", a.token.loadErr, len(a.token.tokens) > 0) {
			return
		}
		// A new term is a new query over the whole collection, so it re-reads from
		// the first page: keeping the old offset would show "page 3" of a result
		// set that may hold three rows. This runs before the empty-state branch,
		// because a search that matches nothing leaves the previous rows in place
		// and would otherwise be recorded as applied without ever being read —
		// the next term then found the old list still showing.
		searchChanged := a.token.search != a.token.appliedSearch
		if searchChanged {
			a.token.appliedSearch = a.token.search
			// The highlight indexes the rows the new query returns; after a new
			// term the same index is a different token, so no row stays chosen.
			a.token.chosen = -1
			a.loadTokenPage(0)
		}
		// The count is announced before either empty branch: "0 results" is the
		// answer a screen reader needs, and it is the same fact the empty note
		// states visually.
		announceSearchResults(c, searchChanged, len(a.token.tokens))
		if a.waitForWrite(c, len(a.token.tokens), a.token.loaded) {
			return
		}
		if len(a.token.tokens) == 0 {
			// An empty result is not always an empty store, and the store's state is
			// what decides which sentence is true. A store with no tokens gets the
			// first-record guide even when a term is open — the guide's create is the
			// only way forward. A store with tokens gets "no match", because clearing
			// the field is the fix and the guide's advice would be wrong.
			// A search that has never seen a term-less read cannot say whether the
			// store is empty; ask it once, so a query restored from an earlier
			// session still tells "nothing stored" from "nothing matched".
			if !a.token.storeChecked && a.services != nil {
				if all, err := a.services.ListTokens(0, 0); err == nil {
					a.token.storeEmpty = len(all) == 0
					a.token.storeChecked = true
				}
			}
			if a.token.storeEmpty {
				emptyState(c, pageToken, "No tokens yet", "Create the first token below; the list, forms and history follow it.")
				return
			}
			emptyNote(c, fmt.Sprintf(tr("No tokens match “%s”."), strings.TrimSpace(a.token.appliedSearch)))
			return
		}
		previous, next := collectionToolbar(c, &a.token.search, "Search tokens",
			"Search matches id, name or symbol across the whole collection.",
			"Token collection", a.token.offset, len(a.token.tokens), a.token.hasMore)
		if previous || next {
			target := a.token.offset
			if previous {
				target = max(0, target-tokenPageSize)
			} else {
				target += tokenPageSize
			}
			if a.loadTokenPage(target) {
				a.token.chosen = -1
			}
			return
		}
		// The rows already answer the applied term: storage selected them. Filtering
		// again by the field would double-count and, worse, disagree with storage
		// about what a term matches, so the list is exactly what was read.
		rows := a.token.tokens
		collectionList(c, "Token collection",
			collectionRecords(rows, tokenCollectionRecord),
			a.token.chosen, func(i int) { a.chooseToken(rows, i) })
	})
}

// tokenCollectionRecord projects a stored token onto the collection record
// the list draws. The supply is a fact beside the name rather than a column at
// the end: it is the number an operator compares, and it should not depend on
// how much room the name happens to leave.
func tokenCollectionRecord(token TokenRow) collectionRecord {
	name := strings.TrimSpace(token.Name)
	if name == "" {
		name = shortID(token.ID)
	}
	return collectionRecord{
		title: name,
		facts: []collectionFact{
			{label: "Symbol", value: valueOr(token.Symbol)},
			{label: "Supply", value: valueOr(token.TotalSupply)},
		},
		fields: []collectionField{{label: "ID", value: token.ID}},
	}
}

// chooseToken is the one selection path shared by the table and the compact
// records. It makes the full row the subject of every other card and re-reads
// whatever detail the previous token left open.
func (a *App) chooseToken(rows []TokenRow, index int) {
	if index < 0 || index >= len(rows) {
		return
	}
	a.token.chosen = index
	chosen := rows[index]
	a.token.tokenID = chosen.ID
	// The owner's public key is known from the record; fill the accounts the
	// write forms ask for and drop the previous token's secrets and recipients.
	a.rememberTokenSubjectOwner(chosen.ID, chosen.Owner)
	a.applyTokenSubject(chosen.Owner)
	// Whatever the Inspect, Balance or History cards show belongs to the
	// previous token; re-read the open ones for the chosen token.
	a.refreshToken()
}

func (a *App) tokenCreate(c *ui.Context) {
	generated := false
	formCard(c, "Create Token", "Define supply and attach the owner key that will authorize future writes.", func() {
		validatedField(c, "Name", &a.token.name, &a.token.nameErr)
		fieldPairError(c, "Symbol", &a.token.symbol, &a.token.symbolErr, "Total Supply", &a.token.supply, &a.token.supplyErr)
		ui.Collapsible(c, tr("Advanced"), &a.token.createAdvanced, func() {
			decimals := ui.Field(c, tr("Decimals"), func() {
				ui.Column(c).Gap(2).Children(func() {
					input := ui.NumberInput(c, &a.token.decimals, 0, 127, 1).
						Description(tr("0 for a whole-unit token; 8 matches most asset conventions."))
					if input.Changed() {
						a.token.decimalsErr = ""
					}
					hint(c, "0 for a whole-unit token; 8 matches most asset conventions.")
				})
			})
			attachFieldError(c, decimals, "Decimals", a.token.decimalsErr)
		})
		fieldHint(c, "Owner (base64 public key)", "Required: the owner signs every later mint, transfer and burn.", &a.token.owner)
		ui.Row(c).Gap(space2).Children(func() {
			if secondaryButton(c, "Generate key pair").Bind(&a.token.generateControl).Clicked() {
				generated = a.generateTokenOwner()
			}
			if a.token.ownerPriv != "" && quietButton(c, "Dismiss key").Clicked() {
				a.token.ownerPriv = ""
				a.token.generateControl.Focus(c)
			}
		})
		if a.token.ownerPriv != "" {
			copyRow(c, "Owner private key", a.token.ownerPriv, func() {
				a.token.status = okStatus("Owner private key copied.")
			}).Bind(&a.token.ownerKeyCopy)
			ui.Text(c, tr("This is the only copy of the owner key; the store keeps the public half.")).
				FontSize(textSize(c, 11)).TextColor(c.Theme().Warning)
		}
		if generated {
			a.token.ownerKeyCopy.Focus(c)
		}
		ui.Row(c).Children(func() {
			if primaryButton(c, "Create Token", allSet(a.token.name, a.token.symbol, a.token.supply, a.token.owner)).Clicked() {
				a.createToken()
			}
		})
	})
}

// generateTokenOwner fills the Owner field from a fresh Ed25519 key pair and
// offers the private half for copying. Without it the window could not create
// a token without a key generator outside the app, while the CLI generates one
// when the flag is omitted.
func (a *App) generateTokenOwner() bool {
	pub, priv, err := a.services.GenerateKeyPair()
	if err != nil {
		a.token.status = errStatus(err)
		return false
	}
	a.token.owner, a.token.ownerPriv = pub, priv
	// A newly generated pair belongs to no token yet; do not let the write
	// forms reuse it against the last token created with another key.
	a.token.ownerKeyTokenID = ""
	a.token.status = okStatus("Generated an owner key pair. Copy the private key now; it is not stored.")
	return true
}

func (a *App) createToken() {
	a.token.status = statusLine{}
	a.token.decimalsErr = ""
	decimals := int(a.token.decimals)
	if float64(decimals) != a.token.decimals || decimals < 0 || decimals > 127 {
		a.token.decimalsErr = "Decimals must be a whole number between 0 and 127."
		a.token.createAdvanced = true
		return
	}
	name, symbol := strings.TrimSpace(a.token.name), strings.TrimSpace(a.token.symbol)
	supply, owner := strings.TrimSpace(a.token.supply), strings.TrimSpace(a.token.owner)
	if rejectIncomplete(&a.token.status, "Token name, symbol, supply, and owner are required.", name, symbol, supply, owner) {
		return
	}
	// The store enforces these bounds and its refusal names no field. Running the
	// domain's own validators here puts the same sentences on the two controls
	// they apply to, and using the domain's wording is what keeps the window from
	// describing a rule the store does not apply.
	a.token.nameErr, a.token.symbolErr, a.token.supplyErr = "", "", ""
	if err := token.ValidateTokenName(name); err != nil {
		a.token.nameErr = err.Error()
		return
	}
	if err := token.ValidateTokenSymbol(symbol); err != nil {
		a.token.symbolErr = err.Error()
		return
	}
	// The supply is the one create field the store parses as a number, and its
	// refusal names no field. Running the same parser here puts the sentence under
	// the control that needs fixing, and its wording is the store's own.
	if _, err := token.NewAmountFromString(supply); err != nil {
		a.token.supplyErr = err.Error()
		return
	}
	ownerPriv := a.token.ownerPriv
	a.runWrite("Creating token…", func() func() {
		t, err := a.services.CreateToken(name, symbol, supply, owner, decimals)
		return func() {
			if err != nil {
				a.token.status = errStatus(err)
				return
			}
			a.token.status = okStatus("Created %s (%s) with supply %s. Owner: %s", t.Name, t.Symbol, t.TotalSupply, t.Owner)
			a.token.tokenID = t.ID
			a.token.ownerKeyTokenID = t.ID
			// The list is the page's entry point, so a new token joins it at once;
			// the readouts that were open move to the new token with it, and the
			// account fields start from the owner instead of asking for the same
			// public key six times.
			a.rememberSuccessfulKey(t.Owner, ownerPriv)
			a.rememberTokenSubjectOwner(t.ID, t.Owner)
			a.applyTokenSubject(t.Owner)
			a.refreshTokenAt(0)
			a.selectTokenByID(t.ID)
			a.token.name, a.token.symbol, a.token.supply = "", "", ""
		}
	})
}

// applyTokenSubject points every owner-shaped field at the selected token's
// owner and clears the secrets, recipients and spenders that belonged to the
// previous subject. Public keys are safe to repeat; carrying a private key or
// an old recipient across a subject change is how an operator signs or sends
// for the wrong account.
func (a *App) applyTokenSubject(owner string) {
	a.token.mintPriv, a.token.xPriv, a.token.approvePriv = "", "", ""
	a.token.fromPriv, a.token.burnPriv = "", ""
	a.token.xTo, a.token.approveTo, a.token.fromTo, a.token.allowanceTo = "", "", "", ""
	a.token.mintTo, a.token.xFrom, a.token.approveOwner = "", "", ""
	a.token.fromOwner, a.token.burnFrom, a.token.allowanceOwner = "", "", ""
	a.token.balanceAccount, a.token.historyOwner = "", ""
	a.token.fromSpender = ""
	a.token.allowance = ""
	a.token.allowanceErr = nil
	a.token.allowanceLoadedToken, a.token.allowanceLoadedOwner, a.token.allowanceLoadedTo = "", "", ""
	a.token.subjectID = strings.TrimSpace(a.token.tokenID)
	if owner == "" {
		return
	}
	a.token.mintTo = owner
	a.token.xFrom = owner
	a.token.approveOwner = owner
	a.token.fromOwner = owner
	a.token.burnFrom = owner
	a.token.allowanceOwner = owner
	a.token.balanceAccount = owner
	a.token.historyOwner = owner
}

// syncTokenSubject reacts to a Token ID typed directly into the Inspect field.
// Row selection, creation and a successful Inspect already move the owner
// context explicitly; this covers the remaining entry path before any write
// form can be submitted with the previous token's account values.
func (a *App) syncTokenSubject() {
	id := strings.TrimSpace(a.token.tokenID)
	if a.token.subjectID == id {
		return
	}
	a.applyTokenSubject(a.selectedTokenOwner())
}

func (a *App) rememberTokenSubjectOwner(id, owner string) {
	a.token.resolvedOwnerID = strings.TrimSpace(id)
	a.token.resolvedOwner = strings.TrimSpace(owner)
}

// selectTokenByID highlights a record in the collection after a create. The
// list is newest first, so the new row is normally index 0; looking it up
// still holds if a store returns another order.
func (a *App) selectTokenByID(id string) {
	a.token.search, a.token.appliedSearch = "", ""
	a.token.chosen = -1
	for i, token := range a.token.tokens {
		if token.ID == id {
			a.token.chosen = i
			return
		}
	}
}

// tokenSubject names the token every write on this page acts on.
//
// The cards take no token id of their own: they all use a.token.tokenID, which
// Create and Inspect set. Without saying so, the right-hand column gave no
// sign of which token a Mint would hit — the one thing an operator must be
// sure of before a write.
func tokenSubject(c *ui.Context, id string) {
	actionSubject(c, id, "No token selected", "Choose one in the list, or create a token.",
		"Copy token ID", "Token ID is on the clipboard")
}

// refreshToken re-reads everything the page shows: the collection (whose rows
// show total supply), an open Inspect readout, a shown balance and a loaded
// history. A write or the Refresh button must not leave stale numbers beside
// a successful result.
func (a *App) refreshToken() {
	a.refreshTokenAt(a.token.offset)
}

// refreshTokenAt re-reads the collection at offset and everything else the
// page shows. A create uses offset zero without moving the pager ahead of a
// failed list read.
func (a *App) refreshTokenAt(offset int) {
	a.loadTokenPage(offset)
	id := strings.TrimSpace(a.token.tokenID)

	// A readout is open if it holds rows or a failure from the last attempt.
	// Re-read it for the current subject; invalidate it first when the subject
	// or query changed, so a failed read cannot leave the previous answer on
	// screen under the new input.
	if a.token.info != nil || a.token.infoLoadedID != "" || a.token.infoErr != nil {
		a.clearTokenInfoForAnotherSubject(id)
		_ = a.loadTokenInfo(id)
	}
	if a.token.balance != "" || a.token.balanceLoadedToken != "" ||
		a.token.balanceLoadedOwner != "" || a.token.balanceErr != nil {
		owner := strings.TrimSpace(a.token.balanceAccount)
		a.clearTokenBalanceForAnotherRead(id, owner)
		_ = a.loadTokenBalance(id, owner)
	}
	if len(a.token.history) > 0 || a.token.historyLoadedToken != "" ||
		a.token.historyLoadedOwner != "" || a.token.historyErr != nil {
		limit, offset := a.tokenHistoryWindow()
		owner := strings.TrimSpace(a.token.historyOwner)
		a.clearTokenHistoryForAnotherRead(id, owner, limit, offset)
		_ = a.loadTokenHistory(id, owner, limit, offset)
	}
	if a.token.allowanceLoadedToken != "" || a.token.allowanceErr != nil {
		owner := strings.TrimSpace(a.token.allowanceOwner)
		spender := strings.TrimSpace(a.token.allowanceTo)
		a.clearAllowanceForAnotherRead(id, owner, spender)
		_ = a.loadTokenAllowance(id, owner, spender)
	}
}

// wrapErr turns a service call's error into the page's status line, and a nil
// error into a success line.
func wrapErr(err error) statusLine {
	if err != nil {
		return errStatus(err)
	}
	return okStatus("Done.")
}
