package nativeui

import (
	"fmt"
	"strings"

	"github.com/egoist/mygo/ui"
)

func (a *App) nftWrite(c *ui.Context) {
	tabs(c, &a.nft.opTab, "NFT actions", tr("Transfer"), tr("Burn"), tr("History"))
	switch a.nft.opTab {
	case 0:
		formCard(c, "Transfer", "Move an NFT to a new owner; the transfer is signed by the current one.", func() {
			field(c, "NFT ID", &a.nft.transferID)
			field(c, "From (base64 public key)", &a.nft.from)
			field(c, "To (base64 public key)", &a.nft.to)
			field(c, "From Private Key", &a.nft.priv)
			a.useCreatorKeyButton(c, &a.nft.priv, a.nft.transferID, a.nft.from)
			a.useSavedKeyButton(c, a.nft.from, &a.nft.priv)
			ui.Row(c).Children(func() {
				if primaryButton(c, "Transfer", allSet(a.nft.transferID, a.nft.from, a.nft.to, a.nft.priv)).Clicked() {
					a.transferNFT()
				}
			})
		})

	case 1:
		formCard(c, "Burn", "Destroy an NFT permanently. This cannot be undone.", func() {
			field(c, "NFT ID", &a.nft.burnID)
			field(c, "Owner (base64 public key)", &a.nft.burnOwner)
			field(c, "Owner Private Key", &a.nft.burnPriv)
			a.useCreatorKeyButton(c, &a.nft.burnPriv, a.nft.burnID, a.nft.burnOwner)
			a.useSavedKeyButton(c, a.nft.burnOwner, &a.nft.burnPriv)
			burnReady := allSet(a.nft.burnID, a.nft.burnOwner, a.nft.burnPriv)
			ui.Row(c).Children(func() {
				// A destructive action carries the danger style, and the
				// confirmation still stands between it and the write.
				burn := dangerButton(c, "Burn NFT…", burnReady).Bind(&a.nft.burnTrigger)
				if burn.Clicked() {
					a.nft.askBurn = true
				}
			})
		})

	case 2:
		formCard(c, "History", "Every mint, transfer and burn recorded for this NFT.", func() {
			field(c, "NFT ID", &a.nft.historyID)
			ui.Row(c).Children(func() {
				if secondaryButton(c, "Show History", allSet(a.nft.historyID)).Clicked() {
					a.readNFTHistory()
				}
			})
			id := strings.TrimSpace(a.nft.historyID)
			matches := id != "" && a.nft.historyLoadedID == id
			if a.nft.historyErr != nil && matches &&
				!loadWarning(c, "Couldn't load NFT history", a.nft.historyErr, len(a.nft.history) > 0) {
				return
			}
			if !matches {
				if id == "" {
					// The id can only come from the collection or a paste, so
					// an empty field is a missing first step, not an empty read.
					emptyNote(c, "Choose an asset in Collection or enter its ID first.")
				} else {
					emptyNote(c, "No history loaded yet.")
				}
				return
			}
			a.nftHistoryTable(c)
		})
	}
}

// useCreatorKeyButton offers the private key generated by the Mint card to a
// transfer or burn that still signs as the creator. It disappears once the
// asset has moved to another owner or another asset is the subject.
func (a *App) useCreatorKeyButton(c *ui.Context, target *string, nftID, holder string) {
	if a.nft.creatorPriv == "" || a.nft.creatorKeyNFTID == "" ||
		a.nft.creatorKeyNFTID != strings.TrimSpace(nftID) ||
		strings.TrimSpace(holder) != a.nft.creator {
		return
	}
	if quietButton(c, "Use generated creator key").Clicked() {
		*target = a.nft.creatorPriv
	}
}

// transferNFT moves the asset named by the Transfer card.
func (a *App) transferNFT() {
	privateKey := strings.TrimSpace(a.nft.priv)
	id := strings.TrimSpace(a.nft.transferID)
	from, to := strings.TrimSpace(a.nft.from), strings.TrimSpace(a.nft.to)
	if rejectIncomplete(&a.nft.status, "NFT ID, sender, recipient, and private key are required.", id, from, to, privateKey) {
		return
	}
	a.runWrite("Transferring NFT…", func() func() {
		err := a.services.TransferNFT(id, from, to, privateKey)
		return func() {
			a.nft.status = wrapErr(err)
			if err == nil {
				a.rememberSuccessfulKey(from, privateKey)
				// The recipient is the asset's holder now. Move both holder-shaped
				// forms only when they target this asset; Transfer and Burn have
				// independent ids, so a write to one must not retarget the other.
				a.applyNFTTransferSubject(to)
				if strings.TrimSpace(a.nft.burnID) == id {
					a.applyNFTBurnSubject(to)
				}
				a.refreshNFT(id)
			}
		}
	})
}

func (a *App) renderNFTBurnDialog(c *ui.Context) {
	if !a.nft.askBurn {
		return
	}
	// Say which asset is about to be destroyed. A name is friendlier than a
	// UUID, but only when the Inspect card loaded that same asset.
	detail := tr("The asset is destroyed and cannot be recovered.")
	if id := strings.TrimSpace(a.nft.burnID); id != "" {
		target := shortID(id)
		if a.nft.nft != nil && a.nft.nft.ID == id && a.nft.nft.Name != "" {
			target = conciseText(a.nft.nft.Name, 32) + " (" + shortID(id) + ")"
		}
		detail = fmt.Sprintf(tr("Burn %s? The asset is destroyed and cannot be recovered."), target)
	}
	switch destructiveConfirm(c, &a.nft.askBurn, "Burn this NFT?", detail, "Burn",
		a.nft.burnTrigger, a.nft.burnTrigger) {
	case destructiveConfirmed:
		id := strings.TrimSpace(a.nft.burnID)
		privateKey := strings.TrimSpace(a.nft.burnPriv)
		owner := strings.TrimSpace(a.nft.burnOwner)
		if !allSet(id, owner, privateKey) {
			a.nft.status = errorStatus("NFT ID, owner, and private key are required.")
			return
		}
		a.runWrite("Burning NFT…", func() func() {
			err := a.services.BurnNFT(id, owner, privateKey)
			return func() {
				a.nft.status = wrapErr(err)
				if err == nil {
					a.rememberSuccessfulKey(owner, privateKey)
					a.nft.burnPriv = ""
					// The asset is gone, so reading it again is not a failure to
					// report: clear the Inspect card directly and re-read the history,
					// which now ends with the burn.
					a.loadNFT()
					if a.nft.nftLoadedID == id || (a.nft.nft != nil && a.nft.nft.ID == id) {
						a.nft.nft = nil
						a.nft.nftErr = nil
						a.nft.nftLoadedID = ""
					}
					if a.nft.historyLoadedID == id {
						_ = a.loadNFTHistory(id)
					}
				}
			}
		})
	}
}
